% fix the artifacts at the ice front created by AMR. 
function md=fix_ice_front(md, config, ice_front_x, param_func, folder_name)
    md=ISSMModelUtils.ReinitializeAMRModel(md, 'ParamFunc', param_func);
    md=ISSMParamUtils.init_BC(md, 'NoSlip', true, 'IceTongueX', ice_front_x);
    md=ISSMModelUtils.RunTransient("final_md", [], [],...
                            'SaveModel', true,...
                            'SavePrevious', false, ...
                            'NumProc', config.NUM_PROC, ...
                            'TimeStep', config.TIME_STEP, ...
                            'OutputFreq', config.AMR_INTERP_SETTINGS.OUTPUT_FREQ, ...
                            'TimeLength', config.AMR_INTERP_SETTINGS.NUM_YRS,... 
                            'UseAMR', false, ...
                            'AMRFrequency', 0, ...
                            'SavePath', [config.SAVE_PATH folder_name], ...
                            'RestartModel', md, ...
                            'MeltRate', 0.0, ...
                            'SurfaceMassBalance', config.SURFACE_MASS_BALANCE, ...
                            'InterpolateForcings', false, ...
                            'ExecutionPath', config.EXECUTION_PATH);

end