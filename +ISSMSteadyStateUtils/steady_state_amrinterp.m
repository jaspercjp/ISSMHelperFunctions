%STEADY_STATE_AMRINTERP: Interpolates a simulation using ISSM's AMR capability 
% given an ISSM model, the configuration file used to genreate
% that simulation, the parametrization function used to parametrize the physics and/or
% geometry of that simulation, and the folder name where the results will be stored.
function md_reinit = steady_state_amrinterp(md, config, param_func, folder_name)
    % Output + execution roots come from the environment (exported by the
    % launcher: $DATA_ROOT / $ISSM_EXECUTION_ROOT), and an unset
    % DATA_ROOT is an error rather than a hard-coded site path.
    data_root = getenv('DATA_ROOT');
    if isempty(data_root)
        error('ISSMHelperFunctions:noDataRoot', 'DATA_ROOT is not set; the launchers (Core.issm_run, _calc_steady_state.sh) export it.');
    end
    exec_root = getenv('ISSM_EXECUTION_ROOT');
    if isempty(exec_root)
        exec_root = fullfile(data_root, 'ISSM_execution');
    end
    config.LOAD_PATH = [fullfile(data_root, 'steady_states') filesep];
    config.SAVE_PATH = [fullfile(data_root, 'steady_states') filesep];
    config.EXECUTION_PATH = [exec_root filesep];

    % md_reinit=ISSMModelUtils.ReinitializeAMRModel(md, 'ParamFunc', param_func);
    % md_reinit=ISSMParamUtils.init_BC(md_reinit, 'NoSlip', true, 'IceTongueX', -1);
    md_reinit = transientrestart(md);
    md_reinit=ISSMModelUtils.RunTransient('md_amr_interp', [], [],...
                             'SaveModel', true,...
                             'NumProc', config.NUM_PROC, ...
                             'TimeStep', config.TIME_STEP, ...
                             'OutputFreq', config.AMR_INTERP_SETTINGS.OUTPUT_FREQ, ...
                             'TimeLength', config.AMR_INTERP_SETTINGS.NUM_YRS,... 
                             'UseAMR', true, ...
                             'AMRSetting', config.AMR_SETTING, ...
                             'SavePath', [config.SAVE_PATH folder_name], ...
                             'RestartModel', md_reinit, ...
                             'SavePrevious', false, ...
                             'SurfaceMassBalance', config.SURFACE_MASS_BALANCE, ...
                             'ExecutionPath', config.EXECUTION_PATH);

end
